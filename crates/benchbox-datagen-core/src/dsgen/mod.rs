use model::Model;

pub(crate) struct LineItem {
    pub(crate) item_sk: i64,
    pub(crate) is_returned: bool,
}

const OWN_TABLES: [&str; 9] = [
    "catalog_returns",
    "catalog_sales",
    "customer",
    "inventory",
    "promotion",
    "store_returns",
    "store_sales",
    "web_returns",
    "web_sales",
];

pub(crate) fn generates(table: &str, scale_factor: f64) -> bool {
    scale_factor < FULL_MODEL_SCALE_FACTOR && OWN_TABLES.contains(&table)
}

pub(crate) fn rows(
    table: &str,
    scale_factor: f64,
    range: RangeInclusive<u64>,
) -> Box<dyn Iterator<Item = String> + Send> {
    let model = Model::new(scale_factor);
    let (first, last) = (*range.start(), *range.end());
    macro_rules! lines {
        ($rows:expr) => {
            Box::new($rows.map(|row| row.to_string()))
        };
    }
    match table {
        "customer" => lines!(dimensions::CustomerRows::new(model, first, last)),
        "promotion" => lines!(dimensions::PromotionRows::new(model, first, last)),
        "inventory" => lines!(dimensions::InventoryRows::new(model, first, last)),
        "store_sales" => lines!(store::StoreSalesRows::new(model, first, last)),
        "store_returns" => lines!(store::StoreReturnsRows::new(model, first, last)),
        "catalog_sales" => lines!(catalog::CatalogSalesRows::new(model, first, last)),
        "catalog_returns" => lines!(catalog::CatalogReturnsRows::new(model, first, last)),
        "web_sales" => lines!(web::WebSalesRows::new(model, first, last)),
        "web_returns" => lines!(web::WebReturnsRows::new(model, first, last)),
        other => unreachable!("table {other:?} is generated by tpcdsgen"),
    }
}

pub(crate) fn batches(
    rows: Box<dyn Iterator<Item = String> + Send>,
    schema: SchemaRef,
) -> BatchReader {
    Box::new(batch::DatBatches::new(rows, schema))
}

#[cfg(test)]
mod tests {
    use std::fmt::Display;

    use tpcdsgen::config::{CompatMode, Session, SessionBuilder, Table};
    use tpcdsgen::row::{
        CatalogReturnsRowGenerator, CatalogSalesRowGenerator, CustomerRowGenerator,
        InventoryRowGenerator, PromotionRowGenerator, StoreReturnsRowGenerator,
        StoreSalesRowGenerator, WebReturnsRowGenerator, WebSalesRowGenerator,
    };

    use super::*;

    fn upstream_session() -> Session {
        SessionBuilder::new()
            .with_scale_factor(1.0)
            .with_compat_mode(CompatMode::C)
            .build()
            .expect("session")
    }

    fn lines<R: Display>(rows: impl Iterator<Item = R>) -> Vec<String> {
        rows.map(|row| row.to_string()).collect()
    }

    #[test]
    fn the_model_at_scale_factor_one_equals_upstream_scaling() {
        let session = upstream_session();
        let scaling = session.get_scaling();
        let model = Model::new(1.0);
        for &table in Table::values() {
            if table == Table::DbgenVersion {
                continue;
            }
            assert_eq!(model.rows(table), scaling.get_row_count(table), "{table:?}");
            assert_eq!(model.ids(table), scaling.get_id_count(table), "{table:?}");
        }
        for table in [Table::StoreSales, Table::CatalogSales, Table::WebSales] {
            for julian in [2_450_815, 2_451_000, 2_451_545, 2_452_640] {
                assert_eq!(
                    model.rows_for_date(table, julian),
                    scaling.get_row_count_for_date(table, julian),
                    "{table:?} {julian}"
                );
            }
        }
    }

    macro_rules! equals_upstream {
        ($name:ident, $table:literal, $upstream:ident, $source:expr, $first:expr, $last:expr) => {
            #[test]
            fn $name() {
                let session = upstream_session();
                let source_rows = $source(&session);
                let mut upstream = $upstream::new(session, source_rows);
                upstream.set_source_row_range($first, $last);
                let expected = lines(upstream);
                let actual: Vec<String> = rows($table, 1.0, $first..=$last).collect();
                assert!(!expected.is_empty());
                assert_eq!(actual, expected);
            }
        };
    }

    fn source_rows(table: Table) -> impl Fn(&Session) -> u64 {
        move |session| session.get_scaling().get_row_count(table)
    }

    equals_upstream!(
        customer_equals_upstream,
        "customer",
        CustomerRowGenerator,
        source_rows(Table::Customer),
        1,
        3_000
    );
    equals_upstream!(
        promotion_equals_upstream,
        "promotion",
        PromotionRowGenerator,
        source_rows(Table::Promotion),
        1,
        300
    );
    equals_upstream!(
        inventory_equals_upstream,
        "inventory",
        InventoryRowGenerator,
        source_rows(Table::Inventory),
        5_000,
        9_000
    );
    equals_upstream!(
        store_sales_equals_upstream,
        "store_sales",
        StoreSalesRowGenerator,
        source_rows(Table::StoreSales),
        40,
        120
    );
    equals_upstream!(
        store_returns_equals_upstream,
        "store_returns",
        StoreReturnsRowGenerator,
        source_rows(Table::StoreSales),
        40,
        400
    );
    equals_upstream!(
        catalog_sales_equals_upstream,
        "catalog_sales",
        CatalogSalesRowGenerator,
        source_rows(Table::CatalogSales),
        40,
        120
    );
    equals_upstream!(
        catalog_returns_equals_upstream,
        "catalog_returns",
        CatalogReturnsRowGenerator,
        source_rows(Table::CatalogSales),
        40,
        400
    );
    equals_upstream!(
        web_sales_equals_upstream,
        "web_sales",
        WebSalesRowGenerator,
        source_rows(Table::WebSales),
        40,
        120
    );
    equals_upstream!(
        web_returns_equals_upstream,
        "web_returns",
        WebReturnsRowGenerator,
        source_rows(Table::WebSales),
        40,
        400
    );

    #[test]
    fn subscale_ranges_concatenate_to_the_whole_table() {
        for table in OWN_TABLES {
            let whole: Vec<String> = rows(table, 0.01, 1..=u64::MAX).collect();
            let model = Model::new(0.01);
            let total = match table {
                "catalog_sales" | "catalog_returns" => model.rows(Table::CatalogSales),
                "web_sales" | "web_returns" => model.rows(Table::WebSales),
                "store_sales" | "store_returns" => model.rows(Table::StoreSales),
                "customer" => model.rows(Table::Customer),
                "promotion" => model.rows(Table::Promotion),
                _ => model.rows(Table::Inventory),
            };
            let middle = total / 2;
            let mut parts: Vec<String> = rows(table, 0.01, 1..=middle).collect();
            parts.extend(rows(table, 0.01, middle + 1..=total));
            assert!(!whole.is_empty(), "{table}");
            assert_eq!(parts, whole, "{table}");
        }
    }
}
